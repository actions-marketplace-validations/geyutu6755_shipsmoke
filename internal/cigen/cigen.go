// Package cigen generates CI workflow files for `shipsmoke init --ci`.
//
// Scope contract: ShipSmoke does NOT infer how a project builds. The
// supported stacks are exactly the three generated here — go, rust, c —
// using their standard toolchains and the same build/package/verify shape
// proven end-to-end in the shipsmoke-integration repository. Anything else
// is out of scope and users are told so.
package cigen

import (
	"fmt"
	"strings"
)

// Stack identifies a supported, fully-generated CI scenario.
type Stack string

const (
	StackGo   Stack = "go"
	StackRust Stack = "rust"
	StackC    Stack = "c"
)

// ParseStack validates the --stack value with an actionable error.
func ParseStack(s string) (Stack, error) {
	switch Stack(strings.ToLower(strings.TrimSpace(s))) {
	case StackGo:
		return StackGo, nil
	case StackRust:
		return StackRust, nil
	case StackC:
		return StackC, nil
	case "":
		return "", fmt.Errorf("--stack is required for --ci; supported stacks: go, rust, c (shipsmoke does not infer build systems)")
	default:
		return "", fmt.Errorf("unknown stack %q: supported stacks are go, rust, c (shipsmoke does not infer arbitrary build systems; copy .github/workflows/example-*.yml from the repository for other setups)", s)
	}
}

// ValidateName checks the binary/tool name used in build and config files.
func ValidateName(name string) error {
	if name == "" {
		return fmt.Errorf("--name is required (the tool's binary name, e.g. \"mytool\")")
	}
	if len(name) > 64 {
		return fmt.Errorf("name %q is too long", name)
	}
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_', r == '.':
		default:
			return fmt.Errorf("name %q contains %q: use letters, digits, '-', '_', '.'", name, string(r))
		}
	}
	return nil
}

// third-party actions, pinned to commit SHAs (see docs/SUPPLY_CHAIN.md)
const (
	shaCheckout = "actions/checkout@11d5960a326750d5838078e36cf38b85af677262"        // v4
	shaSetupGo  = "actions/setup-go@40f1582b2485089dde7abd97c1529aa768e1baff"        // v5
	shaUpload   = "actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02" // v4
	// shipsmokeActionVersion is the tool release the generated workflow pins.
	shipsmokeActionVersion = "v1.0.3"
)

// Generate returns the .shipsmoke.yml and .github/workflows/shipsmoke.yml
// contents for the stack and tool name. The generated workflow follows the
// exact build/package/verify shape proven in shipsmoke-integration.
func Generate(stack Stack, name string) (config string, workflow string, err error) {
	if err := ValidateName(name); err != nil {
		return "", "", err
	}
	return shipsmokeYAML(name), workflowYAML(stack, name), nil
}

func shipsmokeYAML(name string) string {
	unixChecks := fmt.Sprintf(`  - name: %[1]s-unix
    path: dist/%[1]s.tar.gz
    binary: %[1]s
    runs_on: [linux/amd64, linux/arm64, darwin/amd64, darwin/arm64]
    checks:
      - args: ["--version"]
        expect:
          exit_code: 0
          stdout_contains: ["%[1]s"]
`, name)
	winChecks := fmt.Sprintf(`  - name: %[1]s-windows
    path: dist/%[1]s.zip
    binary: %[1]s.exe
    runs_on: [windows/amd64, windows/arm64]
    checks:
      - args: ["--version"]
        expect:
          exit_code: 0
          stdout_contains: ["%[1]s"]
`, name)
	return fmt.Sprintf(`version: 1

# Generated by shipsmoke init --ci. Verifies your packaged release artifacts
# on every platform they target. Reference: docs/CONFIGURATION.md
report:
  json: dist/shipsmoke-report.json

artifacts:
%[1]s%[2]s`, unixChecks, winChecks)
}

func workflowYAML(stack Stack, name string) string {
	var setup, build string
	switch stack {
	case StackGo:
		setup = fmt.Sprintf(`      - uses: %[1]s
        with:
          go-version: 'stable'`, shaSetupGo)
		build = `          go build -o "dist/%[1]s$EXE" .`
	case StackRust:
		setup = `      # The Rust toolchain is preinstalled on GitHub-hosted runners.`
		build = `          cargo build --release
          if [ "$RUNNER_OS" = "Windows" ]; then cp target/release/%[1]s.exe dist/%[1]s.exe; else cp target/release/%[1]s dist/%[1]s; fi`
	case StackC:
		setup = `      # cc (Linux/macOS) and gcc (Windows runners) are preinstalled.`
		build = `          if [ "$RUNNER_OS" = "Windows" ]; then gcc -O2 -o "dist/%[1]s.exe" %[1]s.c; else cc -O2 -o "dist/%[1]s" %[1]s.c; fi`
	}
	build = fmt.Sprintf(build+"\n", name)
	return fmt.Sprintf(`name: shipsmoke

on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:

permissions:
  contents: read

jobs:
  verify:
    name: Verify release artifact (${{ matrix.os }})
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-24.04, macos-15, windows-2025]
    runs-on: ${{ matrix.os }}
    steps:
      - uses: %[3]s

%[4]s

      - name: Build and package the release artifact
        shell: bash
        run: |
          set -euo pipefail
          EXE=""
          [ "$RUNNER_OS" = "Windows" ] && EXE=".exe"
          mkdir -p dist
%[5]s          if [ "$RUNNER_OS" = "Windows" ]; then
            powershell -NoProfile -Command "Compress-Archive -Path dist/%[1]s.exe -DestinationPath dist/%[1]s.zip -Force"
          else
            tar -czf dist/%[1]s.tar.gz -C dist %[1]s
          fi

      # ShipSmoke: verify the packaged artifact really extracts and runs on
      # this OS. Any failed check fails this job and blocks publish steps
      # that depend on it.
      - name: Verify artifact with shipsmoke
        uses: geyutu6755/shipsmoke@v1
        with:
          config: .shipsmoke.yml
          report: dist/shipsmoke-report.json
          version: %[2]s

      - name: Upload verification report
        if: always()
        uses: %[6]s
        with:
          name: shipsmoke-report-${{ matrix.os }}
          path: dist/shipsmoke-report.json
          if-no-files-found: ignore
`, name, shipsmokeActionVersion, shaCheckout, setup, build, shaUpload)
}
